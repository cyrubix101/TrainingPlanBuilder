public class Run {
    public double date;
    public String name;
    public double milage;

    public Run(double date, String name, double milage) {
        this.date = date;
        this.name = name;
        this.milage = milage;
    }

    public double getDate() {
        return date;
    }
    public String getName() {
        return name;
    }
    public double getMilage() {
        return milage;
    }



}
